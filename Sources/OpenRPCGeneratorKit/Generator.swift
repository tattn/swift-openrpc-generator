import Foundation

/// The access level of generated code.
public enum AccessLevel: String, CaseIterable, Sendable {
    case `public`
    case `package`
    case `internal`

    /// The modifier prepended to declarations (omitted for internal).
    var prefix: String {
        switch self {
        case .public: return "public "
        case .package: return "package "
        case .internal: return ""
        }
    }
}

/// A generated code component. Models and the runtime are always emitted;
/// the client and server are selectable.
public enum GeneratedComponent: String, CaseIterable, Sendable {
    case client
    case server
}

public struct GeneratorOptions: Sendable {
    /// The type name of the generated client. When nil, it is derived from info.title.
    public var clientName: String?
    public var accessLevel: AccessLevel
    public var components: Set<GeneratedComponent>

    public init(
        clientName: String? = nil,
        accessLevel: AccessLevel = .public,
        components: Set<GeneratedComponent> = [.client, .server]
    ) {
        self.clientName = clientName
        self.accessLevel = accessLevel
        self.components = components
    }
}

public struct GeneratedFile: Sendable {
    public let name: String
    public let contents: String
}

public struct GeneratorOutput: Sendable {
    public let files: [GeneratedFile]
    public let warnings: [String]
}

/// Generates Swift client and server code from an OpenRPC document.
public struct OpenRPCSwiftGenerator: Sendable {
    public let document: OpenRPCDocument
    public let options: GeneratorOptions

    public init(document: OpenRPCDocument, options: GeneratorOptions = GeneratorOptions()) {
        self.document = document
        self.options = options
    }

    public func generate() -> GeneratorOutput {
        let context = CodegenContext(document: document)
        let baseName = Self.baseName(of: options.clientName ?? SwiftNaming.typeName(document.info.title))
        let clientName = options.clientName ?? baseName + "Client"
        let access = options.accessLevel
        let header = """
            // Generated by swift-openrpc-generator from \(document.info.title) v\(document.info.version).
            // Do not edit manually.
            """

        // Generate components/schemas first; inline types discovered while
        // resolving methods are appended after them, then the error enum.
        context.generateComponentModels()
        let methods = context.resolveMethods()
        let errorTypeName = context.declareErrorEnum(baseName: baseName)

        var files = [
            GeneratedFile(
                name: "\(baseName)Models.swift",
                contents: ModelsRenderer(access: access).render(
                    decls: context.modelDecls,
                    header: header
                )
            )
        ]
        if !methods.notifications.isEmpty {
            // The name goes through the registry too, so it cannot collide
            // with schema types of the same name.
            let notificationsRenderer = NotificationsRenderer(
                access: access,
                typeName: context.uniqueTypeName(baseName + "Notification")
            )
            files.append(
                GeneratedFile(
                    name: "\(notificationsRenderer.typeName).swift",
                    contents: notificationsRenderer.render(
                        notifications: methods.notifications,
                        header: header
                    )
                ))
        }
        if options.components.contains(.client) {
            files.append(
                GeneratedFile(
                    name: "\(clientName).swift",
                    contents: ClientRenderer(access: access, clientName: clientName, errorTypeName: errorTypeName)
                        .render(methods: methods.calls, header: header)
                ))
        }
        if options.components.contains(.server) {
            // These names go through the registry too, so they cannot
            // collide with schema types of the same names.
            let serverRenderer = ServerRenderer(
                access: access,
                handlerName: context.uniqueTypeName(baseName + "Handler"),
                serverName: context.uniqueTypeName(baseName + "Server")
            )
            files.append(
                GeneratedFile(
                    name: "\(serverRenderer.serverName).swift",
                    contents: serverRenderer.render(methods: methods.calls, header: header)
                ))
        }
        files.append(
            GeneratedFile(
                name: "JSONRPCRuntime.swift",
                contents: RuntimeTemplate.render(access: access, header: header) + "\n"
            ))
        return GeneratorOutput(files: files, warnings: context.warnings)
    }

    /// The prefix shared by all generated top-level names (models file,
    /// server, error enum): the given name without any "Client" suffix.
    private static func baseName(of name: String) -> String {
        guard name.hasSuffix("Client"), name != "Client" else { return name }
        return String(name.dropLast("Client".count))
    }
}
